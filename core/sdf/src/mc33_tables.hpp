// core/sdf/src/mc33_tables.hpp
//
// Marching Cubes 33 (Chernyaev 1995) lookup tables.
//
// Source: Transcribed from Thomas Lewiner, Helio Lopes, Antonio Wilson
// Vieira, Geovan Tavares, "Efficient Implementation of Marching Cubes
// Cases with Topological Guarantees", Journal of Graphics Tools 8(2),
// 2003 (public domain). The transcription was verified against the
// reference tables in the shwilks/rmarchingcubes R package (which is a
// cleaned-up copy of Lewiner's original C++ code). See:
//
//   * Chernyaev, E.V. (1995). "Marching Cubes 33: Construction of
//     Topologically Correct Isosurfaces". CERN-CN-95-17.
//     https://cds.cern.ch/record/389230
//   * Lewiner et al. (2003). https://thomas.lewiner.org/pdfs/
//   * Vega, Abache, Coll (2019). "A Fast and Memory-Saving Marching
//     Cubes 33 implementation with the correct interior test",
//     JCGT 8(3), 1-18. http://jcgt.org/published/0008/03/01/
//   * Custodio, Etiene, Pesco, Silva (2013). "Practical considerations
//     on Marching Cubes 33 topological correctness".
//     https://doi.org/10.1016/j.cag.2013.04.004
//
// This header provides:
//
//   1. kTriangleTable[256][16]      — the "classic" MC table
//                                      (Paul Bourke / Lorensen & Cline).
//                                      Each row is up to 5 triangles
//                                      (3 edge indices each) terminated
//                                      by -1. This is the format that
//                                      CAD_0's mesh_extract.cpp already
//                                      uses, but with the Lewiner
//                                      winding order.
//
//   2. kCases[256][2]                — MC33 case dispatch. For each
//                                      cube_index, {case, config}
//                                      selects which tiling table to
//                                      use. Cases 3, 4, 6, 7, 10, 12,
//                                      13 are "ambiguous" and require
//                                      additional face / interior
//                                      tests to select a sub-case.
//
//   3. kTiling1 .. kTiling14        — per-case triangulations. Each
//                                      tiling row gives the edge
//                                      indices (0..11) of one
//                                      triangle. A value of 12 means
//                                      "cube-center vertex" (v12),
//                                      which must be added as an extra
//                                      vertex inside the cube.
//
//   4. kTest3, kTest4, kTest6,
//      kTest7, kTest10, kTest12,
//      kTest13, kSubconfig13         — ambiguity-resolution tables.
//                                      These tell you which face(s)
//                                      of the cube to test, and
//                                      (optionally) which interior
//                                      test to perform. A negative
//                                      value means "invert the result
//                                      of the test".
//
//   5. kCornerLookup[6][4]           — the 4 corner indices for each of
//                                      the 6 cube faces, used by the
//                                      asymptotic decider
//                                      (face-center test).
//
//   6. kAmbiguousCubeIndexSet        — a sorted list of the cube_index
//                                      values that require ambiguity
//                                      resolution. Useful for unit
//                                      tests that want to exercise
//                                      every ambiguous case.
//
// Cube vertex numbering (matches mesh_extract.cpp kCornerOffset):
//
//       3 ___________ 2
//       /|           /|
//      / |          / |
//   4 /___________ 5/  |        z
//    |   |        |   |        |   y
//    |   |        |   |        |  /
//    |   0________|___1         | /____x
//    |  /         |  /          (right-handed)
//    | /          | /
//    |/___________|/
//    7            6
//
//   Vertex 0 = (0,0,0)    bit 0 in cube_index = (1<<0) = 0x01
//   Vertex 1 = (1,0,0)    bit 1 in cube_index = (1<<1) = 0x02
//   Vertex 2 = (1,1,0)    bit 2 in cube_index = (1<<2) = 0x04
//   Vertex 3 = (0,1,0)    bit 3 in cube_index = (1<<3) = 0x08
//   Vertex 4 = (0,0,1)    bit 4 in cube_index = (1<<4) = 0x10
//   Vertex 5 = (1,0,1)    bit 5 in cube_index = (1<<5) = 0x20
//   Vertex 6 = (1,1,1)    bit 6 in cube_index = (1<<6) = 0x40
//   Vertex 7 = (0,1,1)    bit 7 in cube_index = (1<<7) = 0x80
//
// Edge numbering (matches mesh_extract.cpp kEdgeCorners):
//
//   Edge 0  = v0–v1    Edge 4  = v4–v5    Edge 8  = v0–v4
//   Edge 1  = v1–v2    Edge 5  = v5–v6    Edge 9  = v1–v5
//   Edge 2  = v2–v3    Edge 6  = v6–v7    Edge 10 = v2–v6
//   Edge 3  = v3–v0    Edge 7  = v7–v4    Edge 11 = v3–v7
//
//   Edge 12 (synthetic) = cube center, used by MC33 sub-cases that
//   require an interior vertex (v12).
//
// Face numbering (per Lewiner / Chernyaev). Faces are numbered 1..6:
//
//   Face 1 (front, y=0): corners {0, 4, 5, 1}
//   Face 2 (right, x=1): corners {1, 5, 6, 2}
//   Face 3 (back,  y=1): corners {2, 6, 7, 3}
//   Face 4 (left,  x=0): corners {3, 7, 4, 0}
//   Face 5 (bottom, z=0): corners {0, 3, 2, 1}
//   Face 6 (top,    z=1): corners {4, 7, 6, 5}
//
// A face is "ambiguous" when its 4 corners have an alternating sign
// pattern (2 inside, 2 outside, diagonally placed). The asymptotic
// decider selects between the two possible triangulations of that
// face by sampling the value at the face center:
//
//   For a face with corners A,B,C,D (in the order listed above),
//   let f(t,u) = (1-t)(1-u)A + t(1-u)B + tu C + (1-t)u D
//   be the bilinear interpolant on the face. The face center is
//   f(1/2, 1/2) = (A+B+C+D)/4. There's also an analytical test:
//   the face is "inside-connected along A-C" iff A*C - B*D >= 0.
//   The test in this implementation is:
//
//       test_face(face, cube) returns true iff
//           face * A * (A*C - B*D) >= 0
//
//   where face > 0 selects "inside-along-A-C" and face < 0
//   inverts the decision.
//
// Interior test: needed for cases 4, 6, 7, 10, 12, 13 when the
// face tests are inconclusive. The interior test samples the
// trilinear interpolant along a "reference edge" of the cube
// (specified per case by the test table's last column) and
// decides whether the center of the cube is "inside" the surface.
//
